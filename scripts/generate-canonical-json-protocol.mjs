#!/usr/bin/env node
// Generate a self-contained snapshot from agent-method-registry's public
// canonical-json-v1 protocol. Public packages verify the snapshot digest
// without reading a sibling checkout; parent integration supplies --authority.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(root, 'scripts/lib/generated/canonical-json-v1.generated.mjs');
const vectorsOutputPath = join(root, 'scripts/lib/generated/canonical-json-v1-vectors.generated.json');
const manifestPath = join(root, 'scripts/lib/generated/canonical-json-v1-manifest.json');
const check = process.argv.includes('--check');

if (check) {
  const [output, vectors, manifestText] = await Promise.all([
    readFile(outputPath, 'utf8'),
    readFile(vectorsOutputPath, 'utf8'),
    readFile(manifestPath, 'utf8'),
  ]);
  const manifest = JSON.parse(manifestText);
  if (manifest.schemaVersion !== 1 || manifest.protocol !== 'canonical-json-v1' ||
      manifest.outputDigest !== digest(output) ||
      manifest.vectorsDigest !== digest(vectors) ||
      !output.includes(`authority digest: ${manifest.authorityDigest}`)) {
    throw new Error('canonical-json-v1 generated snapshot drift');
  }
  const authorityFlag = process.argv.indexOf('--authority');
  if (authorityFlag >= 0) {
    const authorityPath = process.argv[authorityFlag + 1];
    if (!authorityPath) throw new Error('--authority requires a path');
    const [authority, authorityVectors] = await Promise.all([
      readFile(authorityPath, 'utf8'),
      readFile(join(dirname(authorityPath), 'canonical-json-v1-vectors.json'), 'utf8'),
    ]);
    const expectedOutput = renderOutput(authority);
    if (manifest.authorityDigest !== digest(authority) ||
        output !== expectedOutput ||
        manifest.outputDigest !== digest(expectedOutput) ||
        vectors !== authorityVectors) {
      throw new Error('canonical-json-v1 authority mismatch');
    }
  }
} else {
  const authorityFlag = process.argv.indexOf('--authority');
  if (authorityFlag < 0 || !process.argv[authorityFlag + 1]) {
    throw new Error('generation requires --authority <canonical-json-v1.mjs>');
  }
  const authorityPath = process.argv[authorityFlag + 1];
  const [authority, vectors] = await Promise.all([
    readFile(authorityPath, 'utf8'),
    readFile(join(dirname(authorityPath), 'canonical-json-v1-vectors.json'), 'utf8'),
  ]);
  if (!authority.includes('Canonical JSON v1')) throw new Error('invalid canonical-json-v1 authority source');
  const authorityDigest = digest(authority);
  const output = renderOutput(authority);
  await writeFile(outputPath, output);
  await writeFile(vectorsOutputPath, vectors);
  await writeFile(manifestPath, `${JSON.stringify({
    schemaVersion: 1,
    protocol: 'canonical-json-v1',
    authorityDigest,
    outputDigest: digest(output),
    vectorsDigest: digest(vectors),
  }, null, 2)}\n`);
}

function digest(value) {
  return `sha256:${createHash('sha256').update(value).digest('hex')}`;
}

function renderOutput(authority) {
  return `// Generated by scripts/generate-canonical-json-protocol.mjs.\n// authority digest: ${digest(authority)}\n${authority}`;
}
