#!/usr/bin/env node
// @feature ACA18 @scenario S-65 @decision D-ACA-18
// Compile authoritative JSON Schemas into dependency-free ESM validators.
// Generation loads Ajv only in the development/build path. --check is itself
// dependency-free and verifies schema, generator, and output digests recorded
// in the generated manifest.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const root = dirname(dirname(scriptPath));
const check = process.argv.includes('--check');
const generatedRoot = join(root, 'scripts/lib/generated');
const manifestPath = join(generatedRoot, 'schema-validator-manifest.json');
const definitions = [
  {
    name: 'family-api',
    schema: join(root, 'family-apis/schema/family-api.schema.json'),
    output: join(generatedRoot, 'family-api-validator.generated.mjs'),
  },
  {
    name: 'project-facts',
    schema: join(root, 'schemas/project-facts.schema.json'),
    output: join(generatedRoot, 'project-facts-validator.generated.mjs'),
  },
];

const generatorDigest = digest(await readFile(scriptPath));

if (check) {
  await checkGeneratedArtifacts();
} else {
  await generateArtifacts();
}

async function generateArtifacts() {
  const [{ default: Ajv }, { default: standaloneCode }] = await Promise.all([
    import('ajv'),
    import('ajv/dist/standalone/index.js'),
  ]);
  const entries = [];
  for (const definition of definitions) {
    const schemaText = await readFile(definition.schema, 'utf8');
    const schema = JSON.parse(schemaText);
    const schemaDigest = digest(schemaText);
    const ajv = new Ajv({
      allErrors: true,
      strict: false,
      code: { source: true, esm: true, lines: true },
    });
    const validate = ajv.compile(schema);
    const standalone = inlineAjvRuntimeDependencies(standaloneCode(ajv, validate));
    const generated = [
      '// This file is generated by scripts/generate-schema-validators.mjs.',
      `// Source: ${definition.name}; schema digest: ${schemaDigest}; generator digest: ${generatorDigest}`,
      standalone,
      `export const schemaDigest = ${JSON.stringify(schemaDigest)};`,
      '',
    ].join('\n');
    await mkdir(dirname(definition.output), { recursive: true });
    await writeFile(definition.output, generated);
    entries.push({
      name: definition.name,
      schemaPath: relative(root, definition.schema),
      schemaDigest,
      outputPath: relative(root, definition.output),
      outputDigest: digest(generated),
    });
  }
  const manifest = { schemaVersion: 1, generatorDigest, entries };
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

async function checkGeneratedArtifacts() {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch (error) {
    process.stderr.write(`Schema validator manifest missing or invalid: ${error.message}\n`);
    process.exitCode = 1;
    return;
  }
  let drift = false;
  if (manifest.schemaVersion !== 1 || manifest.generatorDigest !== generatorDigest) {
    process.stderr.write('Schema validator drift: generator digest mismatch\n');
    drift = true;
  }
  for (const definition of definitions) {
    const entry = manifest.entries?.find(candidate => candidate.name === definition.name);
    try {
      const [schemaText, outputText] = await Promise.all([
        readFile(definition.schema, 'utf8'),
        readFile(definition.output, 'utf8'),
      ]);
      const valid = entry
        && entry.schemaPath === relative(root, definition.schema)
        && entry.outputPath === relative(root, definition.output)
        && entry.schemaDigest === digest(schemaText)
        && entry.outputDigest === digest(outputText)
        && !/require\(["']ajv|from ["']ajv|import\(["']ajv/.test(outputText);
      if (!valid) {
        process.stderr.write(`Schema validator drift: ${relative(root, definition.output)}\n`);
        drift = true;
      }
    } catch (error) {
      process.stderr.write(`Schema validator drift: ${definition.name}: ${error.message}\n`);
      drift = true;
    }
  }
  if (manifest.entries?.length !== definitions.length) {
    process.stderr.write('Schema validator drift: manifest entry count mismatch\n');
    drift = true;
  }
  if (drift) process.exitCode = 1;
}

function digest(value) {
  return `sha256:${createHash('sha256').update(value).digest('hex')}`;
}

function inlineAjvRuntimeDependencies(source) {
  return source.replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    `const $1 = function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length++;
    let value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
};`,
  );
}
